const Pattern& pattern_at(int index) {
  return kPatterns[static_cast<std::size_t>(clamp_pattern_index(index))];
}

int clamp_pattern_index(int index) {
  if (index < 0) {
    return 0;
  }
  if (index >= kPatternCount) {
    return kPatternCount - 1;
  }
  return index;
}

void apply_pattern_mask(std::uint8_t* rgba, int width, int height, int stride,
                        const std::uint8_t* mask, const Pattern& pattern, Color fg, Color bg,
                        Rect* dirty) {
  if (rgba == nullptr || mask == nullptr || width < 1 || height < 1) {
    return;
  }
  int minx = width;
  int miny = height;
  int maxx = -1;
  int maxy = -1;
  for (int y = 0; y < height; ++y) {
    for (int x = 0; x < width; ++x) {
      if (mask[static_cast<std::size_t>(y) * static_cast<std::size_t>(width) +
               static_cast<std::size_t>(x)] == 0) {
        continue;
      }
      const Color c = pattern.color_at(x, y, fg, bg);
      std::uint8_t* p = rgba + static_cast<std::size_t>(y) * stride + static_cast<std::size_t>(x) * 4;
      p[0] = c.r;
      p[1] = c.g;
      p[2] = c.b;
      p[3] = c.a;
      minx = std::min(minx, x);
      miny = std::min(miny, y);
      maxx = std::max(maxx, x);
      maxy = std::max(maxy, y);
    }
  }
  if (dirty != nullptr && maxx >= minx) {
    *dirty = rect_union(*dirty, Rect{minx, miny, maxx - minx + 1, maxy - miny + 1});
  }
}

